// Generates server/lib/limits.php from packages/core/src/model.ts, the single source of the caps,
// the colour keys, the note fields and the HTTP status of every error code. `npm run check:limits`
// fails when the committed file differs from what this script writes. Never edit limits.php by hand.
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
export const target = path.join(root, 'server/lib/limits.php');

function literal(value, depth = 1) {
  if (typeof value === 'number') {
    if (!Number.isSafeInteger(value)) throw new Error(`Only integers can be generated, got ${value}`);
    return String(value);
  }
  if (typeof value === 'string') return `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;
  if (Array.isArray(value)) return `[${value.map(v => literal(v, depth + 1)).join(', ')}]`;
  if (value && typeof value === 'object') {
    const pad = '  '.repeat(depth);
    const rows = Object.entries(value).map(([k, v]) => `${pad}${literal(k)} => ${literal(v, depth + 1)},`);
    return `[\n${rows.join('\n')}\n${'  '.repeat(depth - 1)}]`;
  }
  throw new Error(`Cannot generate ${typeof value}`);
}

export async function render() {
  const model = await import(pathToFileURL(path.join(root, 'packages/core/src/model.ts')).href);
  const { CAPS, CHORE_DAYS, CHORE_MARK_STATES, CHORE_MONTHS, CHORE_NTHS, CHORE_WEEKS, COLOR_KEYS, DEFAULT_COLORS, ERROR_STATUS, NOTE_FIELDS, PERSON_ROLES, STORE_VERSION } = model;
  const shared = {
    storeVersion: STORE_VERSION,
    // Roles only, never an account: which account holds each role is the server's private config (server/lib/people.php).
    personRoles: [...PERSON_ROLES],
    colorKeys: [...COLOR_KEYS],
    // [role, color] pairs (array_column(..., 1, 0) reads them as a map): a role is never a key that maps to a bare string here.
    defaultColorsByRole: Object.entries(DEFAULT_COLORS),
    noteFields: Object.fromEntries(Object.entries(NOTE_FIELDS).map(([scope, fields]) => [scope, [...fields]])),
    choreDays: [...CHORE_DAYS],
    choreWeeks: [...CHORE_WEEKS],
    choreMonths: [...CHORE_MONTHS],
    choreNths: [...CHORE_NTHS],
    choreMarkStates: [...CHORE_MARK_STATES],
    errorStatus: { ...ERROR_STATUS },
  };
  return `<?php
// Generated by tools/gen-limits.mjs from packages/core/src/model.ts. Do not edit by hand:
// run \`node tools/gen-limits.mjs\`. \`npm run check:limits\` fails on any difference.
declare(strict_types=1);
namespace PlanMind;

/** Mirrors CAPS. Text lengths count Unicode code points, never bytes. */
const LIMITS = ${literal(CAPS)};

/** Mirrors the other shared constants of model.ts that the server validates against. */
const MODEL = ${literal(shared)};
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const text = await render();
  if (process.argv.includes('--stdout')) process.stdout.write(text);
  else { writeFileSync(target, text); console.log(`Wrote ${path.relative(root, target)}.`); }
}
