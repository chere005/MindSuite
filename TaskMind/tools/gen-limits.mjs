// Generates server/lib/limits.php from packages/core/src/model.ts, the single source of the caps, the roles and
// permission matrix, the member-id shape, the seed team and the HTTP status of every error code.
// `npm run check:limits` fails when the committed file differs from what this script writes. Never edit limits.php by hand.
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
export const target = path.join(root, 'server/lib/limits.php');

function literal(value, depth = 1) {
  if (typeof value === 'number') {
    if (!Number.isSafeInteger(value)) throw new Error(`Only integers can be generated, got ${value}`);
    return String(value);
  }
  if (typeof value === 'string') return `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;
  if (Array.isArray(value)) return `[${value.map(v => literal(v, depth + 1)).join(', ')}]`;
  if (value && typeof value === 'object') {
    const pad = '  '.repeat(depth);
    const rows = Object.entries(value).map(([k, v]) => `${pad}${literal(k)} => ${literal(v, depth + 1)},`);
    return `[\n${rows.join('\n')}\n${'  '.repeat(depth - 1)}]`;
  }
  throw new Error(`Cannot generate ${typeof value}`);
}

export async function render() {
  const model = await import(pathToFileURL(path.join(root, 'packages/core/src/model.ts')).href);
  const { CAPS, ERROR_STATUS, HEALTH, ID_PATTERN, KINDS, MATRIX, PRIORITIES, PROJECT_ACTIONS, REPLAYABLE_OPS, ROLES, STATUSES, STORE_VERSION, VISIBILITIES } = model;
  const shared = {
    storeVersion: STORE_VERSION,
    idPattern: ID_PATTERN,
    roles: [...ROLES],
    matrix: Object.fromEntries(Object.entries(MATRIX).map(([action, roles]) => [action, [...roles]])),
    projectActions: [...PROJECT_ACTIONS],
    replayableOps: [...REPLAYABLE_OPS],
    visibilities: [...VISIBILITIES],
    statuses: [...STATUSES],
    priorities: [...PRIORITIES],
    kinds: [...KINDS],
    health: [...HEALTH],
    errorStatus: { ...ERROR_STATUS },
  };
  return `<?php
// Generated by tools/gen-limits.mjs from packages/core/src/model.ts. Do not edit by hand:
// run \`node tools/gen-limits.mjs\`. \`npm run check:limits\` fails on any difference.
declare(strict_types=1);
namespace TaskMind;

/** Mirrors CAPS. Text lengths count Unicode code points, never bytes. */
const LIMITS = ${literal(CAPS)};

/** Mirrors the other shared constants of model.ts that the server validates against. */
const MODEL = ${literal(shared)};
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const text = await render();
  if (process.argv.includes('--stdout')) process.stdout.write(text);
  else { writeFileSync(target, text); console.log(`Wrote ${path.relative(root, target)}.`); }
}
